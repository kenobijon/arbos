#!/usr/bin/env bash
# Rewrite /etc/arbos/download.caddy so that https://relay.arbos.life/download/mac (and
# https://arbos.life/download/mac) 302-redirect to the newest edge-release DMG, then reload Caddy.
# Installed as /usr/local/bin/arbos-refresh-mac-download by scripts/deploy/relay-server.sh and run
# by arbos-refresh-mac-download.timer every 15 minutes.
set -euo pipefail
OUT=/etc/arbos/download.caddy
RELOAD=1
[[ "${1:-}" == "--no-reload" ]] && RELOAD=0

json=$(curl -fsSL "https://api.github.com/repos/unarbos/arbos/releases?per_page=20")
dmg=$(printf '%s' "$json" | python3 -c '
import sys, json
rels = [r for r in json.load(sys.stdin) if r["tag_name"].startswith("edge-")]
for r in rels:
    for a in r["assets"]:
        if a["name"].endswith(".dmg"):
            print(a["browser_download_url"]); sys.exit(0)
')
[[ -n "$dmg" ]] || { echo "refresh-mac-download: no DMG in the edge releases" >&2; exit 1; }

mkdir -p /etc/arbos
new=$(printf '# generated by arbos-refresh-mac-download on %s\nredir /download/mac %s 302\nredir /download/mac/ %s 302\n' "$(date -u +%FT%TZ)" "$dmg" "$dmg")
if [[ -f "$OUT" ]] && [[ "$(grep -v '^#' "$OUT")" == "$(printf '%s' "$new" | grep -v '^#')" ]]; then
  exit 0
fi
printf '%s\n' "$new" > "$OUT"
chmod 0644 "$OUT"
echo "download/mac → $dmg"
if [[ $RELOAD -eq 1 ]] && systemctl is-active --quiet arbos-www.service; then
  systemctl reload arbos-www.service || true
fi
