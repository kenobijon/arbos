#!/usr/bin/env bash
# Generate Swift Codable structs from arbos-core #[typeshare] types into
# packages/ArbosFFI/Sources/ArbosFFI/RelayTypes.swift.
#
# Pin must match workspace.dependencies.typeshare and the typeshare-cli version
# installed below. Regenerate after changing crates/arbos-core/src/api.rs (or any
# other #[typeshare] type that should ship to Swift).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

TYPESHARE_CLI_VERSION="1.13.4"
OUT="packages/ArbosFFI/Sources/ArbosFFI/RelayTypes.swift"

if ! command -v typeshare >/dev/null 2>&1 \
  || [[ "$(typeshare --version 2>/dev/null | awk '{print $NF}')" != "$TYPESHARE_CLI_VERSION" ]]; then
  echo "Installing typeshare-cli == $TYPESHARE_CLI_VERSION (locked)…"
  cargo install typeshare-cli --version "$TYPESHARE_CLI_VERSION" --locked --force
fi

mkdir -p "$(dirname "$OUT")"
TMP="$(mktemp)"
# Only emit types marked #[typeshare]. serialized_as = String keeps wire::BoxState
# out of the Swift module so it does not clash with UniFFI's BoxState.
typeshare \
  crates/arbos-core \
  --lang=swift \
  --output-file="$TMP"

{
  echo "// Generated by scripts/gen-swift-types.sh — do not edit."
  echo "// Source: crates/arbos-core (#[typeshare] types). Regenerate: ./scripts/gen-swift-types.sh"
  echo
  cat "$TMP"
} >"$OUT"
rm -f "$TMP"

echo "Wrote $OUT"
